import Foundation
import SweetArrowsCore

/// Markdown report with the difficulty of every level.
public enum Report {
    public static func markdown(_ levels: [Level], seed: UInt64) -> String {
        var lines: [String] = []
        lines.append("# Level report")
        lines.append("")
        lines.append("Generated by `swift run levelgen` (seed `0x\(String(seed, radix: 16, uppercase: true))`). "
            + "Every level below was approved by the solver: it can be won without a single bounce "
            + "and without filling the jar.")
        lines.append("")
        lines.append("- **Difficulty** 0–100: board size, colors, traps, jar pressure and special elements.")
        lines.append("- **Traps**: moves along the solution that are allowed but make the level unwinnable.")
        lines.append("- **Solutions**: winning move orders (capped at 10,000).")
        lines.append("")

        // Per-world summary.
        lines.append("## Worlds")
        lines.append("")
        lines.append("| World | Levels | New element | Avg difficulty | Hardest |")
        lines.append("|---|---|---|---|---|")
        let byWorld = Dictionary(grouping: levels, by: \.world)
        for world in byWorld.keys.sorted() {
            let group = byWorld[world]!
            let difficulties = group.compactMap { $0.stats?.difficulty }
            let avg = difficulties.isEmpty ? 0 : difficulties.reduce(0, +) / Double(difficulties.count)
            let w = World(id: world)
            let name = w.theme.displayName + (w.season > 1 ? " \(w.season)" : "")
            lines.append("| \(world). \(name) | \(group.first!.id)–\(group.last!.id) | "
                + "\(w.newElement?.displayName ?? "–") | \(format(avg)) | \(format(difficulties.max() ?? 0)) |")
        }
        lines.append("")

        lines.append("## Levels")
        lines.append("")
        lines.append("| # | Slot | Board | Candies | Colors | Jar | Elements | Taps | Traps | Solutions | Difficulty | |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
        for level in levels {
            let stats = level.stats
            let slot = level.tutorial ? "tutorial" : Curve.slot(for: level.id).rawValue
            let elements = level.elements.sorted().map(\.displayName).joined(separator: ", ")
            let solutions = stats.map { $0.solutionsCapped ? "≥\($0.solutions)" : "\($0.solutions)" } ?? "?"
            let difficulty = stats.map { format($0.difficulty) } ?? "?"
            let bar = String(repeating: "█", count: Int((stats?.difficulty ?? 0) / 10))
            let colors = Set(level.candies.map(\.color)).count
            lines.append("| \(level.id) | \(slot)\(level.hard ? " 🔥" : "") | \(level.width)×\(level.height) | "
                + "\(level.candies.count) | \(colors) | \(level.bagCapacity) | \(elements.isEmpty ? "–" : elements) | "
                + "\(stats?.solutionLength ?? 0) | \(stats?.pitfalls ?? 0) | \(solutions) | \(difficulty) | \(bar) |")
        }
        lines.append("")
        return lines.joined(separator: "\n")
    }

    private static func format(_ value: Double) -> String {
        String(format: "%.1f", value)
    }
}

public extension World.Theme {
    var displayName: String {
        switch self {
        case .gummyGarden: "Gummy Garden"
        case .lollipopLane: "Lollipop Lane"
        case .chocolateFalls: "Chocolate Falls"
        case .marshmallowMountains: "Marshmallow Mountains"
        case .caramelCanyon: "Caramel Canyon"
        case .cottonCandyClouds: "Cotton Candy Clouds"
        case .licoriceLab: "Licorice Lab"
        case .iceCreamIsland: "Ice Cream Island"
        }
    }
}

public extension BoardElement {
    var displayName: String {
        switch self {
        case .pole: "lollipop pole"
        case .chocolateBar: "chocolate bar"
        case .wrapped: "wrapped"
        case .caramel: "caramel"
        case .iced: "ice"
        case .rotating: "spinner"
        }
    }
}
